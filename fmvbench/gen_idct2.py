"""Writes idct2.dsp: the second pass of saturn/mdec.cpp's IDCT (mdecIdct) on the SCU DSP, bit for bit, for
blocks whose first pass the CPUs have made (docs/ps1-fmv.md).

usage: gen_idct2.py OUT.dsp

A pass's 8 vectors are a block's rows: vector i takes s_j = temp[j][i], the first pass's output (temp[j]
being its vector j's 8 results, as idctPass writes them). Each of the butterfly's steps runs across all 8
vectors at once: a step reads two arrays of 8 (one value a vector) and writes one or two, its counters
stepping through them, which is what the DSP's addressing does well. Products are MUL (32 x 32 -> 48) and
the ALU's AD2 with the accumulator cleared, its upper 32 bits (ALH) being the product >> 16 rounded down:
mdec.cpp's mul(). Sums and differences are its 32-bit ADD and SUB.

The DSP reads an operand pair from two different banks in one instruction, and a step's results go to
banks it isn't reading; the arrays' banks below are chosen so every step keeps to that.

A block comes in as 64 longwords, temp's rows 0 2 3 1 (to bank 0) then 4 6 5 7 (bank 1), and goes out
as 64, the results by column: out[x * 8 + i] = row i's pixel x (the IDCT's [i][x]), columns 0-3 from
bank 2, 4-7 from bank 3.

Data RAM (* set by the SH-2):
  bank 0  0..31 s0 s2 s3 s1   48..51 *K1414 K1847 K2613 K1082   56 *blocks left  57 *in / 4  58 *out / 4
  bank 1  0..31 s4 s6 s5 s7
  banks 0..3 hold the steps' arrays at 8-longword slots (ARRAYS)
"""
import sys

# array -> (bank, slot of 8 longwords); see the docstring
ARRAYS = {
    's0': (0, 0), 's2': (0, 1), 's3': (0, 2), 's1': (0, 3),
    's4': (1, 0), 's6': (1, 1), 's5': (1, 2), 's7': (1, 3),
    'z10': (2, 0), 'z11': (3, 0), 'z13': (3, 1), 'd': (2, 1),
    'm1': (0, 0), 'z12': (2, 1), 't0': (1, 0), 't3': (0, 0), 't1': (0, 1), 't2': (1, 1),
    'z13b': (3, 2), 'z10b': (2, 2), 'z11b': (2, 3), 'z12b': (3, 3),
    'e': (0, 2), 'z5': (1, 2), 'm2': (0, 3), 'u': (3, 0),
    't7': (0, 2), 'f': (1, 3), 't6': (1, 4), 'm3': (2, 0), 't5': (0, 3), 'm4': (2, 1), 'v': (3, 1),
    't4': (1, 2),
    'o0': (2, 0), 'o1': (2, 1), 'o2': (2, 2), 'o3': (2, 3),
    'o4': (3, 0), 'o5': (3, 1), 'o6': (3, 2), 'o7': (3, 3),
}
K_AT = {'k1414': 48, 'k1847': 49, 'k2613': 50, 'k1082': 51}
LEFT, IN_AT, OUT_AT = 56, 57, 58

# mdec.cpp idctPass, step by step: ('pair', a, b, sum, diff), ('add'|'sub', a, b, r) (r = a + b or a - b),
# ('mul', k, x, r) (r = k x x >> 16)
STEPS = [
    ('pair', 's0', 's4', 'z10', 'z11'),
    ('pair', 's2', 's6', 'z13', 'd'),
    ('mul', 'k1414', 'd', 'm1'),
    ('sub', 'm1', 'z13', 'z12'),
    ('pair', 'z10', 'z13', 't0', 't3'),
    ('pair', 'z11', 'z12', 't1', 't2'),
    ('pair', 's3', 's5', 'z13b', 'z10b'),
    ('pair', 's1', 's7', 'z11b', 'z12b'),
    ('sub', 'z12b', 'z10b', 'e'),
    ('mul', 'k1847', 'e', 'z5'),
    ('mul', 'k2613', 'z10b', 'm2'),
    ('add', 'm2', 'z5', 'u'),
    ('pair', 'z11b', 'z13b', 't7', 'f'),
    ('sub', 'u', 't7', 't6'),
    ('mul', 'k1414', 'f', 'm3'),
    ('sub', 'm3', 't6', 't5'),
    ('mul', 'k1082', 'z12b', 'm4'),
    ('sub', 'm4', 'z5', 'v'),
    ('add', 'v', 't5', 't4'),
    ('pair', 't0', 't7', 'o0', 'o7'),
    ('pair', 't1', 't6', 'o1', 'o6'),
    ('pair', 't2', 't5', 'o2', 'o5'),
    ('pair', 't3', 't4', 'o4', 'o3'),
]


def bank(a):
    return ARRAYS[a][0]


def at(a):
    return ARRAYS[a][1] * 8


def check():
    """Each step's banks as the DSP needs them, and no array overwritten while still to be read."""
    for st in STEPS:
        kind = st[0]
        if kind == 'mul':
            _, _, x, r = st
            assert bank(r) != bank(x), st
            continue
        a, b = st[1], st[2]
        outs = st[3:] if kind == 'pair' else st[3:4]
        assert bank(a) != bank(b), st
        for r in outs:
            assert bank(r) not in (bank(a), bank(b)), st
        if kind == 'pair':
            assert bank(outs[0]) != bank(outs[1]), st
    # replay: each slot holds one array at a time; writing over one still to be read fails
    def reads(st):
        return [st[2]] if st[0] == 'mul' else [st[1], st[2]]

    def writes(st):
        return st[3:] if st[0] == 'pair' else st[3:4]

    last = {}
    for i, st in enumerate(STEPS):
        for a in reads(st):
            last[a] = i
    holder = {ARRAYS[s]: s for s in ('s0', 's1', 's2', 's3', 's4', 's5', 's6', 's7')}
    for i, st in enumerate(STEPS):
        for r in writes(st):
            old = holder.get(ARRAYS[r])
            if old is not None and last.get(old, -1) >= i:
                raise AssertionError(f'step {i} writes {r} over {old}, still to be read at step {last[old]}')
            holder[ARRAYS[r]] = r


def emit():
    out = []
    w = out.append
    w('; Generated by fmvbench/gen_idct2.py: the second pass of mdecIdct on the SCU DSP.')
    w('start:')
    w(f'    mov #{IN_AT},ct0')
    w('    mov mc0,ra0')
    w('    mov mc0,wa0')
    w('block:')
    w('    mov #0,ct0')
    w('    mov #0,ct1')
    w('    dma d0,mc0,32')
    w('    dma d0,mc1,32')
    w('wait_in:')
    w('    jmp wait_in,t0')
    w('    nop')
    for n, st in enumerate(STEPS):
        kind = st[0]
        w(f'; {st}')
        if kind == 'pair':
            _, a, b, s, d = st
            w(f'    mov #{at(a)},ct{bank(a)}')
            w(f'    mov #{at(b)},ct{bank(b)}')
            w(f'    mov mc{bank(a)},a | mov mc{bank(b)},p | mov #{at(s)},ct{bank(s)}')
            w(f'    mov #{at(d)},ct{bank(d)}')
            w('    mov #7,lop')
            w(f'    mov #pair{n},top')
            w(f'pair{n}:')
            w(f'    add | mov all,mc{bank(s)}')
            w('    btm')
            w(f'    sub | mov all,mc{bank(d)} | mov mc{bank(a)},a | mov mc{bank(b)},p')
        elif kind in ('add', 'sub'):
            _, a, b, r = st
            w(f'    mov #{at(a)},ct{bank(a)}')
            w(f'    mov #{at(b)},ct{bank(b)}')
            w(f'    mov mc{bank(a)},a | mov mc{bank(b)},p | mov #{at(r)},ct{bank(r)}')
            w('    mov #7,lop')
            w('    lps')
            w(f'    {kind} | mov all,mc{bank(r)} | mov mc{bank(a)},a | mov mc{bank(b)},p')
        else:
            _, k, x, r = st
            w(f'    mov #{K_AT[k]},ct0')
            w(f'    mov mc0,y | mov #{at(x)},ct{bank(x)}')
            w(f'    mov #{at(r)},ct{bank(r)}')
            w(f'    mov mc{bank(x)},x | mov #7,lop')
            w(f'    mov mul,p | mov mc{bank(x)},x | clr a')
            w('    lps')
            w(f'    ad2 | mov mul,p | mov mc{bank(x)},x | clr a | mov alh,mc{bank(r)}')
    w('; the results out, by column: 0-3 from bank 2, 4-7 from bank 3')
    w('    mov #0,ct2')
    w('    mov #0,ct3')
    w('    dma mc2,d0,32')
    w('    dma mc3,d0,32')
    w(f'    mov #{LEFT},ct0')
    w('    mov m0,a | mov #1,pl')
    w('    sub | mov all,mc0')
    w('    jmp block,nz')
    w('    nop')
    w('wait_out:')
    w('    jmp wait_out,t0')
    w('    nop')
    w('    end')
    return '\n'.join(out) + '\n'


def main():
    check()
    text = emit()
    with open(sys.argv[1], 'w', newline='\n') as f:
        f.write(text)


if __name__ == '__main__':
    main()
