const char* fontGlyph(char c)
{
    if (c >= '0' && c <= '9')
        return kDigits[c - '0'];
    if (c >= 'A' && c <= 'Z')
        return kLetters[c - 'A'];
    if (c >= 'a' && c <= 'z')
        return kLetters[c - 'a'];
    return NULL;
}

