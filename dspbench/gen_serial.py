"""Writes serial.dsp: points streamed through the DSP and back, rotated on the
way (dspsched.py), each batch fetched, worked and sent out in turn, waiting
for every transfer: what stream.dsp's overlap is worth.

usage: gen_serial.py OUT.dsp
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from dspsched import rotate_body  # noqa: E402

HEADER = """; Generated by dspbench/gen_serial.py: points streamed through the DSP,
; rotated, a batch fetched, worked and sent out in turn (see the generator).
;
; MD0  0 the output's address / 4  1 the input's / 4  2 batches
;      4..15 the rows: t m0 m1 m2
"""


def main():
    out = [HEADER,
           'serial: mov #1,ct0',
           '        mov m0,ra0',
           '        mov #0,ct0',
           '        mov m0,wa0',
           'batch:  mov #0,ct1',
           '        dma d0,mc1,24',
           'win:    jmp win,t0',
           '        nop',
           '        mov #0,ct1',
           '        mov #4,ct0']
    out += rotate_body(1, 0)
    out += ['        mov #0,ct3',
            '        dma mc3,d0,24',
            'wout:   jmp wout,t0',
            '        nop',
            '        mov #2,ct0',
            '        mov m0,a | mov #1,pl',
            '        sub | mov all,mc0',
            '        jmp batch,nz',
            '        nop',
            '        end']
    with open(sys.argv[1], 'w', newline='\n') as f:
        f.write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
