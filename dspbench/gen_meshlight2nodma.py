"""Writes meshlight2nodma.dsp: meshlight2.dsp with each batch's transfers
(its records and normals in, its output out) a nop in their place, for page
5's measure of what those transfers cost the DSP. The jobs' records still
come in, so that it walks the list. Its output is nothing.

usage: gen_meshlight2nodma.py OUT.dsp
"""
import os
import re
import sys

BATCH_DMA = re.compile(r'\bdma\s+(d0\s*,\s*mc2|mc3\s*,\s*d0)\b')


def main():
    src = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'meshlight2.dsp')
    out = ['; Generated by dspbench/gen_meshlight2nodma.py from meshlight2.dsp: its',
           "; batches' transfers taken out.", '']
    for line in open(src).read().splitlines():
        code, _, _ = line.partition(';')
        if BATCH_DMA.search(code):
            label = re.match(r'(\s*\w+:)?', code).group(1) or ''
            line = label + ' ' * max(1, 8 - len(label)) + 'nop'
        out.append(line)
    with open(sys.argv[1], 'w', newline='\n') as f:
        f.write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
