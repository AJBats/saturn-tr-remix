"""Writes rotate.dsp: the DSP rotating a batch of 8 points by a 3x4 matrix two
ways, for page 2 of the DSP benchmark (page_arithmetic.cpp).

usage: gen_rotate.py OUT.dsp

sched: the way Sonic R's program reads. Three passes, each one row of the
matrix over the 8 points, wholly unrolled, the translation multiplied in as
a fourth term (by 1): the multiplier takes a product and the ALU adds one on
every instruction, and a row's sum is stored as the next row's first product
is taken. 12 instructions a point at best; here a pass ends with one
instruction more, where the points' counter goes back to the first.

plain: the way our programs have been written: a loop over the points, each
point copied beside a 1, then its three rows one after another.
"""
import sys

POINTS = 8

HEADER = """; Generated by dspbench/gen_rotate.py: a batch of 8 points rotated by a 3x4
; matrix, (v . row + t) >> 16 over 48 bits, two ways (see the generator).
;
; Data RAM, set by the SH-2 (page_arithmetic.cpp):
;   MD0  0..23  the points: x y z, 32 bits
;   MD1  0..11  the rows: m0 m1 m2 t
;   MD2  0..23  out: sched x'0..x'7 y'0..y'7 z'0..z'7; plain x' y' z' a point
;   MD3  0 1    1 batches, counted down
; Entries: sched, plain, none (the batch loop alone).
"""


def sched_body():
    """The unrolled batch, a line an instruction."""
    slots = []      # loads, or bubbles with their D1 move
    for row in range(3):
        for k in range(POINTS):
            for j in range(4):
                if j < 3:
                    slots.append({'x': 'mc0', 'y': 'mc1', 'd1': None, 'last': False})
                else:
                    base = row * 4 if k < POINTS - 1 else (row + 1) * 4 % 12
                    slots.append({'x': 'm3', 'y': 'm1', 'd1': f'mov #{base},ct1', 'last': True})
        if row < 2:
            slots.append({'bubble': True, 'd1': 'mov #0,ct0'})
    count = len(slots) + 2
    ins = [{'alu': None, 'x': [], 'y': [], 'd1': None} for _ in range(count)]
    for t, s in enumerate(slots):
        if s.get('bubble'):
            ins[t]['d1'] = s['d1']
            continue
        ins[t]['x'].append(f"mov {s['x']},x")
        ins[t]['y'].append(f"mov {s['y']},y")
        if s['d1']:
            assert ins[t]['d1'] is None, t
            ins[t]['d1'] = s['d1']
        ins[t + 1]['x'].insert(0, 'mov mul,p')
        acc = ins[t + 2]
        acc['alu'] = 'ad2'
        if s['last']:
            acc['y'].insert(0, 'clr a')
            assert acc['d1'] is None, t
            acc['d1'] = 'mov alh,mc2'
        else:
            acc['y'].insert(0, 'mov alu,a')
    ins[1]['y'].insert(0, 'clr a')      # the first row starts from 0
    lines = []
    for i in ins:
        ops = ([i['alu']] if i['alu'] else []) + i['x'] + i['y'] + ([i['d1']] if i['d1'] else [])
        lines.append('        ' + ' | '.join(ops) if ops else '        nop')
    return lines


def main():
    out = [HEADER]
    out.append('sched:  mov #0,ct0')
    out.append('        mov #0,ct1')
    out.append('        mov #0,ct2')
    out.append('        mov #0,ct3')
    out += sched_body()
    out += ['        mov #1,ct3',
            '        mov m3,a | mov #1,pl',
            '        sub | mov all,mc3',
            '        jmp sched,nz',
            '        nop',
            '        end',
            '',
            '        ; each point copied beside a 1 (MD3 8), then a row at a time',
            'plain:  mov #0,ct0',
            '        mov #0,ct1',
            '        mov #0,ct2',
            '        mov #0,ct3',
            '        mov #8,ct3',
            '        mov #1,mc3',
            '        mvi 7,lop',
            '        mov #point,top',
            'point:  mov #5,ct3',
            '        mov mc0,mc3',
            '        mov mc0,mc3',
            '        mov mc0,mc3',
            '        mov #0,ct1',
            '        mov #5,ct3']
    for row in range(3):
        out += ['        mov mc3,x | mov mc1,y',
                '        mov mul,p | mov mc3,x | clr a | mov mc1,y',
                '        ad2 | mov mul,p | mov mc3,x | mov alu,a | mov mc1,y',
                '        ad2 | mov mul,p | mov mc3,x | mov alu,a | mov mc1,y',
                '        ad2 | mov mul,p | mov alu,a | mov #5,ct3']
        if row == 2:
            out.append('        btm')      # the last row's store in its delay slot
        out.append('        ad2 | mov alh,mc2')
    out += ['        mov #1,ct3',
            '        mov m3,a | mov #1,pl',
            '        sub | mov all,mc3',
            '        jmp plain,nz',
            '        nop',
            '        end',
            '',
            'none:   mov #0,ct0',
            '        mov #0,ct1',
            '        mov #0,ct2',
            '        mov #0,ct3',
            '        mov #1,ct3',
            '        mov m3,a | mov #1,pl',
            '        sub | mov all,mc3',
            '        jmp none,nz',
            '        nop',
            '        end']
    with open(sys.argv[1], 'w', newline='\n') as f:
        f.write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
