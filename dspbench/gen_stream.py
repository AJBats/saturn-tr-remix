"""Writes stream.dsp: points streamed from high work RAM through the DSP and
back, rotated on the way (dspsched.py), the way Sonic R streams them: two
input banks, the next batch fetched into one while the other's is worked,
and each batch's results sent out of one half of MD3 while the next batch's
go into the other. No wait in the loop but for a transfer to finish before
the next starts (one transfer at a time).

usage: gen_stream.py OUT.dsp
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from dspsched import rotate_body  # noqa: E402

HEADER = """; Generated by dspbench/gen_stream.py: points streamed through the DSP,
; rotated, overlapping the transfers with the work (see the generator).
;
; MD0  0 the output's address / 4  1 the input's / 4  2 pairs of batches
;      4..15 the rows: t m0 m1 m2
; Each batch is 8 points of x y z (24 longwords) in, x'0..x'7 y'.. z'.. out.
"""


def half(name, bank, other, out_base):
    """A batch's work from bank, the next batch fetched into the other bank a
    little way in, the results sent out at the end."""
    fetch = [f'{name}f: jmp {name}f,t0',
             f'        mov #0,ct{other}',
             f'        dma d0,mc{other},24']
    lines = [f'        mov #0,ct{bank}',
             '        mov #4,ct0']
    lines[0] = f'{name}:' + lines[0][len(name) + 1:]
    lines += rotate_body(bank, out_base, insert_after=16, insert=fetch)
    lines += [f'{name}w: jmp {name}w,t0',
              f'        mov #{out_base},ct3',
              '        dma mc3,d0,24']
    return lines


def main():
    out = [HEADER,
           'stream: mov #1,ct0',
           '        mov m0,ra0',
           '        mov #0,ct0',
           '        mov m0,wa0',
           '        mov #0,ct1',
           '        dma d0,mc1,24',
           'first:  jmp first,t0',
           '        nop']
    out += half('halfa', 1, 2, 0)
    out += half('halfb', 2, 1, 32)
    out += ['        mov #2,ct0',
            '        mov m0,a | mov #1,pl',
            '        sub | mov all,mc0',
            '        jmp halfa,nz',
            '        nop',
            'last:   jmp last,t0',
            '        nop',
            '        end']
    with open(sys.argv[1], 'w', newline='\n') as f:
        f.write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
